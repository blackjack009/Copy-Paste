import AppKit
import CryptoKit
import ImageIO

public struct CaptureOptions: Sendable {
    public var saveImagesAndFiles: Bool
    public var skipSecrets: Bool

    public init(saveImagesAndFiles: Bool = true, skipSecrets: Bool = true) {
        self.saveImagesAndFiles = saveImagesAndFiles
        self.skipSecrets = skipSecrets
    }
}

public struct CapturedClip: Sendable {
    public var item: ClipItem
    public var snapshot: PasteboardSnapshot
    public var thumbnailPNG: Data?
}

/// Turns the current pasteboard contents into a history entry, or nothing when
/// the contents should not be recorded.
public enum ClipCapture {
    /// Marked by apps as transient or machine-made (nspasteboard.org). Never recorded.
    static let alwaysSkippedTypes: Set<String> = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    /// Marked by password managers and similar apps as secret.
    static let secretTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "com.agilebits.onepassword",
        "net.antelle.keeweb",
    ]

    public static func capture(
        from pasteboard: NSPasteboard,
        options: CaptureOptions,
        sourceApp: String?,
        sourceBundleID: String?,
        now: Date = Date()
    ) -> CapturedClip? {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard !types.isEmpty, types.isDisjoint(with: alwaysSkippedTypes) else { return nil }
        if options.skipSecrets, !types.isDisjoint(with: secretTypes) { return nil }

        let snapshot = PasteboardSnapshot.capture(from: pasteboard)
        guard !snapshot.items.isEmpty else { return nil }

        let fileURLs = pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]
        ) as? [URL] ?? []
        let text = pasteboard.string(forType: .string) ?? ""
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)

        var item: ClipItem
        var thumbnail: Data?

        if !fileURLs.isEmpty {
            guard options.saveImagesAndFiles else { return nil }
            item = fileItem(urls: fileURLs)
        } else if let image = imageData(in: snapshot), trimmed.isEmpty || ClipClassifier.isURL(trimmed) {
            // Browsers put the image's address next to the image, so a bare URL
            // does not make this a link. Long text beside an image stays text.
            guard options.saveImagesAndFiles else { return nil }
            item = imageItem(data: image.data, type: image.type)
            thumbnail = thumbnailPNG(from: image.data)
        } else if !trimmed.isEmpty {
            let kind = ClipClassifier.kind(forText: text, sourceBundleID: sourceBundleID)
            item = textItem(text: text, trimmed: trimmed, kind: kind)
        } else {
            return nil
        }

        item.sourceApp = sourceApp
        item.sourceBundleID = sourceBundleID
        item.createdAt = now
        return CapturedClip(item: item, snapshot: snapshot, thumbnailPNG: thumbnail)
    }

    private static func imageData(in snapshot: PasteboardSnapshot) -> (data: Data, type: String)? {
        for type in PasteboardSnapshot.imageTypes {
            for entry in snapshot.items {
                if let data = entry[type] { return (data, type) }
            }
        }
        return nil
    }

    private static func textItem(text: String, trimmed: String, kind: ClipKind) -> ClipItem {
        var detail: String?
        if kind == .color, let rgb = ClipClassifier.rgb(fromHex: trimmed) {
            detail = "rgb(\(rgb.r), \(rgb.g), \(rgb.b))"
        }
        let shown = (kind == .text || kind == .code) ? text : trimmed
        return ClipItem(
            kind: kind,
            text: shown,
            charCount: text.count,
            detail: detail,
            contentHash: hash(Data(text.utf8))
        )
    }

    private static func imageItem(data: Data, type: String) -> ClipItem {
        let format = imageFormatName(type)
        let dimensions = pixelSize(of: data).map { "\($0.width) × \($0.height)" }
        let title = ["Gambar \(format)", dimensions].compactMap { $0 }.joined(separator: ", ")
        let detail = [dimensions, format].compactMap { $0 }.joined(separator: ", ")
        return ClipItem(kind: .image, text: title, charCount: 0, detail: detail, contentHash: hash(data))
    }

    private static func fileItem(urls: [URL]) -> ClipItem {
        let names = urls.map(\.lastPathComponent)
        let title = names.count == 1 ? names[0] : "\(names[0]) dan \(names.count - 1) file lain"
        let paths = urls.map(\.path).joined(separator: "\n")
        return ClipItem(
            kind: .file,
            text: title,
            charCount: 0,
            detail: fileDetail(urls: urls),
            contentHash: hash(Data(paths.utf8))
        )
    }

    private static func fileDetail(urls: [URL]) -> String {
        guard urls.count == 1, let url = urls.first else { return "\(urls.count) file" }
        let values = try? url.resourceValues(forKeys: [.isDirectoryKey, .fileSizeKey])
        if values?.isDirectory == true { return "Folder" }
        let size = Int64(values?.fileSize ?? 0)
        let formatted = ByteCountFormatter.string(fromByteCount: size, countStyle: .file)
        let ext = url.pathExtension.uppercased()
        return ext.isEmpty ? formatted : "\(formatted), \(ext)"
    }

    private static func imageFormatName(_ type: String) -> String {
        switch type {
        case "public.png": return "PNG"
        case "public.jpeg": return "JPEG"
        case "public.tiff": return "TIFF"
        case "com.compuserve.gif": return "GIF"
        case "public.heic": return "HEIC"
        default: return "gambar"
        }
    }

    private static func pixelSize(of data: Data) -> (width: Int, height: Int)? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int else { return nil }
        return (width, height)
    }

    /// A preview-sized PNG, so the list and the preview do not decode the full image.
    static func thumbnailPNG(from data: Data, maxPixelSize: Int = 512) -> Data? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixelSize,
        ]
        guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        return NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:])
    }

    static func hash(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }
}
